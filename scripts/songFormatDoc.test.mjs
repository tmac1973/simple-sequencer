import { describe, it, expect, vi } from 'vitest';
vi.mock('tone', () => ({}));
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FX_DEFS, FX_ORDER } from '../src/audio/effects/registry';
import { CATEGORY_LABEL, PRESETS } from '../src/audio/synthPresets';
import { DEV_SAMPLES } from '../src/audio/devSamples';
import { validateSong } from '../src/model/schema';

/**
 * docs/SONG_FORMAT.md lists every built-in sound, preset and effect. That part is generated
 * from the app's own data so it can't drift: this test fails when it's out of date.
 * Regenerate with:  UPDATE_DOCS=1 npx vitest run --project unit scripts/songFormatDoc
 */
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DOC = resolve(root, 'docs/SONG_FORMAT.md');
const START =
  '<!-- catalog:start (generated by scripts/songFormatDoc.test.mjs; do not edit by hand) -->';
const END = '<!-- catalog:end -->';

const manifest = JSON.parse(readFileSync(resolve(root, 'public/samples/manifest.json'), 'utf8'));

const cell = (s) => String(s).replace(/\|/g, '\\|');
const row = (cells) => `| ${cells.map(cell).join(' | ')} |`;
const secs = (ms) => `${(ms / 1000).toFixed(ms < 1000 ? 2 : 1)} s`;

function catalog() {
  const out = [];

  out.push('### Sample library (`lib:` ids)', '');
  out.push(
    `${manifest.samples.length} sounds in ${manifest.kits.length} kits. Use the **id** as \`sample.sampleId\`. ` +
      'For sounds with a **root note**, set `sample.rootMidi` to it (and usually `sample.melodic: true`) so notes play in tune; ' +
      'for everything else use `rootMidi: 60`.',
    '',
  );
  for (const kit of manifest.kits) {
    const list = manifest.samples.filter((s) => s.kit === kit.id);
    out.push(`#### ${kit.name} (\`${kit.id}\`): ${kit.description}`, '');
    out.push(row(['id', 'name', 'category', 'length', 'root note', 'license']));
    out.push('|---|---|---|---|---|---|');
    for (const s of list)
      out.push(
        row([
          `\`${s.id}\``,
          s.name,
          s.category,
          secs(s.durationMs),
          s.rootNote ?? '',
          `${s.license} (${s.author})`,
        ]),
      );
    out.push('');
  }

  out.push('### Built-in test sounds (`dev:` ids)', '');
  out.push(
    'Simple sounds generated by code. They always load, even offline: ' +
      Object.keys(DEV_SAMPLES)
        .map((k) => `\`${k}\``)
        .join(', ') +
      '.',
    '',
  );

  out.push('### Synth presets (`synth.presetId`)', '');
  out.push(
    '**Octave** is added on top of the note: a bass preset with −1 plays degree 0 one octave lower. ' +
      '**Mono** presets play one note at a time (a new note cuts the last one).',
    '',
  );
  out.push(row(['presetId', 'name', 'category', 'oscillator', 'octave', 'voices']));
  out.push('|---|---|---|---|---|---|');
  for (const p of PRESETS)
    out.push(
      row([
        `\`${p.id}\``,
        p.name,
        CATEGORY_LABEL[p.category],
        p.oscType,
        p.octaveShift > 0 ? `+${p.octaveShift}` : p.octaveShift,
        p.polyphonic ? 'poly' : 'mono',
      ]),
    );
  out.push('');

  out.push('### Effects (`fx[].type` and `fx[].params`)', '');
  out.push(
    'Every param is a number from 0 to 1; a missing param uses its default. **Range** shows what 0, the default and 1 mean. ' +
      'Params marked **auto** can be automated with an `fx` lane.',
    '',
  );
  for (const type of FX_ORDER) {
    const d = FX_DEFS[type];
    out.push(`#### \`${type}\`: ${d.name}. ${d.blurb}`, '');
    out.push(row(['param', 'label', 'default', 'range', 'auto']));
    out.push('|---|---|---|---|---|');
    for (const p of [...d.main, ...d.advanced]) {
      const range = p.choices
        ? p.choices.map((c, i) => `${c} = ${+(i / (p.choices.length - 1)).toFixed(2)}`).join(', ')
        : `0 = ${p.format(0)}; default = ${p.format(p.default)}; 1 = ${p.format(1)}`;
      const auto = d.main.includes(p) && !p.choices ? 'auto' : '';
      out.push(row([`\`${p.key}\``, p.label, p.default, range, auto]));
    }
    out.push('');
  }
  return out.join('\n').trimEnd();
}

describe('docs/SONG_FORMAT.md', () => {
  it('lists the current sounds, presets and effects', () => {
    const doc = readFileSync(DOC, 'utf8');
    const a = doc.indexOf(START);
    const b = doc.indexOf(END);
    expect(a, 'catalog start marker').toBeGreaterThan(-1);
    expect(b, 'catalog end marker').toBeGreaterThan(a);
    const fresh = `${START}\n\n${catalog()}\n\n`;
    const current = doc.slice(a, b);
    if (process.env.UPDATE_DOCS) {
      writeFileSync(DOC, doc.slice(0, a) + fresh + doc.slice(b));
      return;
    }
    expect(
      current,
      'catalog is stale: run UPDATE_DOCS=1 npx vitest run --project unit scripts/songFormatDoc',
    ).toBe(fresh);
  });

  it('example song files are valid and only use built-in sounds and presets', () => {
    const ids = new Set([...manifest.samples.map((s) => s.id), ...Object.keys(DEV_SAMPLES)]);
    const presets = new Set(PRESETS.map((p) => p.id));
    for (const f of ['docs/examples/example-song.json']) {
      const song = validateSong(JSON.parse(readFileSync(resolve(root, f), 'utf8')));
      for (const t of song.tracks) {
        if (t.sample) expect(ids.has(t.sample.sampleId), `${f}: ${t.sample.sampleId}`).toBe(true);
        if (t.synth) expect(presets.has(t.synth.presetId), `${f}: ${t.synth.presetId}`).toBe(true);
      }
    }
  });
});
