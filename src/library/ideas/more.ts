const rhythmChords = (voicings: number[][], rhythm: [number, number][], vel = 0.65, perBar = 16) =>
  chordsOf(
    voicings.flatMap((v, i) =>
      rhythm.map(([s, l]) => [i * perBar + s, l, v] as [number, number, number[]]),
    ),
    vel,
  );

