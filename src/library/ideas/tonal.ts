import { chordsOf, notesOf, type NoteTuple, type PatternIdea } from './model';

/*
 * Notes are scale steps: 0 is the key's home note (octave 3), 7 is the same note an octave up,
 * -7 an octave down. Chords are written as stacks of steps (0,2,4 = the home chord).
 * Times are in 16th steps: 16 per bar.
 */

const bar = (b: number) => b * 16;

/** One held chord per bar. */
const heldChords = (voicings: number[][], len = 15) =>
  chordsOf(voicings.map((v, i) => [bar(i), len, v]));

/** The same rhythm (start, length within a bar) for each bar's chord. */
const rhythmChords = (voicings: number[][], rhythm: [number, number][], vel = 0.65) =>
  chordsOf(
    voicings.flatMap((v, i) =>
      rhythm.map(([s, l]) => [bar(i) + s, l, v] as [number, number, number[]]),
    ),
    vel,
  );

/** Notes on a fixed rhythm: one degree per hit. */
const line = (degrees: number[], every: number, len = every, vel = 0.8): NoteTuple[] =>
  degrees.map((d, i) => [i * every, len, d, i % 2 ? vel - 0.12 : vel]);

